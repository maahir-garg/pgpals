export interface FinalTask {
  week: 1 | 2;
  number: number;
  category: string;
  title: string;
  description: string;
  points: number;
  startDate: string;
  endDate: string;
  type: "standard" | "pair";
  pairTeamCount: number;
  bonusConfig: BonusConfig | null;
}

interface TaskInput {
  week: 1 | 2;
  number: number;
  category: string;
  title: string;
  instructions: string;
  proof: string;
  points: number;
  startDate: string;
  endDate: string;
  groupTeams?: number;
  note?: string;
  bonusConfig?: BonusConfig;
}

function task(input: TaskInput): FinalTask {
  const note = input.note ? `\n\n${input.note}` : "";
  return {
    week: input.week,
    number: input.number,
    category: input.category,
    title: input.title,
    description:
      `**Week ${input.week} · ${input.category} · Challenge ${input.number}**\n\n` +
      `${input.instructions}\n\n**Proof:** ${input.proof}${note}`,
    points: input.points,
    startDate: input.startDate,
    endDate: input.endDate,
    type: input.groupTeams ? "pair" : "standard",
    pairTeamCount: input.groupTeams ?? 2,
    bonusConfig: input.bonusConfig ?? null,
  };
}

