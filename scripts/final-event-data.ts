export function validateFinalEventData() {
  const errors: string[] = [];
  const expectedCounts = new Map<1 | 2, number>([
    [1, 50],
    [2, 50],
  ]);

  for (const [week, expected] of expectedCounts) {
    const tasks = FINAL_TASKS.filter((item) => item.week === week);
    if (tasks.length !== expected) {
      errors.push(`Week ${week} must contain ${expected} tasks; found ${tasks.length}.`);
    }
    const numbers = new Set(tasks.map((item) => item.number));
    for (let number = 1; number <= expected; number += 1) {
      if (!numbers.has(number)) errors.push(`Week ${week} is missing challenge ${number}.`);
    }
  }

  const keys = new Set<string>();
  for (const item of FINAL_TASKS) {
    const key = `${item.week}:${item.number}`;
    if (keys.has(key)) errors.push(`Duplicate challenge key ${key}.`);
    keys.add(key);
    if (!item.title.trim() || !item.description.trim()) {
      errors.push(`${key} needs a title and description.`);
    }
    if (!Number.isInteger(item.points) || item.points < 0) {
      errors.push(`${key} has invalid points.`);
    }
    const releaseAt = Date.parse(`${item.startDate}T00:00:00+08:00`);
    const deadlineAt = Date.parse(`${item.endDate}T23:59:00+08:00`);
    if (!Number.isFinite(releaseAt) || !Number.isFinite(deadlineAt) || deadlineAt <= releaseAt) {
      errors.push(`${key} has invalid dates.`);
    }
    if (item.type === "pair" && (item.pairTeamCount < 2 || item.pairTeamCount > 20)) {
      errors.push(`${key} has invalid group size ${item.pairTeamCount}.`);
    }
    if (item.type === "standard" && item.pairTeamCount !== 2) {
      errors.push(`${key} must use the standard pair-team-count default.`);
    }
  }

  const emails = [...FINAL_RA_ACCOUNTS.map((ra) => ra.email), SHARED_ADMIN_EMAIL];
  if (new Set(emails).size !== emails.length) errors.push("Admin emails must be unique.");
  if (emails.some((email) => email !== email.toLowerCase())) {
    errors.push("Admin emails must be lowercase.");
  }

  if (errors.length > 0) throw new Error(errors.join("\n"));
}
